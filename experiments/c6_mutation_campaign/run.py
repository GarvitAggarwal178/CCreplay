"""C6 stage 1: mutation campaign over user/cubic_model.py's transition logic.

Plan (CCREPLAY_STUDIO_PLAN.md section 5, C6 stage 1): ~20 hand-picked deterministic
mutants, one per operator class x callback (relational swap, +-1 constant,
arithmetic swap, shift +-1, min/max swap, deleted state update), generated by
an `ast` transformer with fixed ids. Classify each: detected (semantic
divergence), crashed (exception, reported separately, not counted as
detected), invalid (fails to load/validate), not exercised (mutated line
never executed, via sys.monitoring line coverage scoped to the containing
function's code object), survived exercised (ran, line executed, but no
disagreement -- possibly equivalent, listed for review). Reports detection
latency (events to first divergence) and the callback it first diverges at.

Does not modify user/cubic_model.py (CLAUDE.md: raw/, data/, user/*.py are
read-only once committed as the reference implementation; mutants are
generated in memory from its source text and never written back there).
Each mutant's AST is compiled directly from the mutated tree (not from an
`ast.unparse` round trip), so unaffected nodes keep the original file's exact
line numbers -- this is what makes line-level coverage tracking meaningful:
"the mutated line" below always means the real line number in
user/cubic_model.py.

Uses ccreplay.diff.all_decisions_core (the same M7 engine primitive that
backs the Studio's "compare all decisions" UI and the Sweep page -- ADR-026:
one shared event loop, no new comparison logic here either) in Mode A
(event-local), against the real reference cubic module, on
raw/cubic_replay/primary/rep1.ccr only (stage 1 scope; rep2/rep3 and Mode B
are stage-2 candidates, not run here -- see summary.md's scope note).
"""
