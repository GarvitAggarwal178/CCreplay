# --------------------------------------------------------------------------
# Mutation targets: each is (func_name, lineno, node_kind) identifying one
# AST node in the real source by its exact line number (read directly off
# user/cubic_model.py), plus an `apply` that mutates that node in place.
# One entry per (operator class, callback) pair, picked to spread across the
# callbacks that carry non-trivial private-state logic (cong_avoid, ssthresh,
# pkts_acked, cwnd_event). init/set_state/undo_cwnd are thin
# wrappers/passthroughs in this model (see cubic_model.py's own docstrings)
# and are out of scope for stage 1, not silently skipped -- noted in
# summary.md.
# --------------------------------------------------------------------------

class Target:
    def __init__(self, mut_id, op_class, callback, func, lineno, node_kind, apply, describe,
                 match_extra=None):
        self.id = mut_id
        self.op_class = op_class
        self.callback = callback
        self.func = func
        self.lineno = lineno
        self.node_kind = node_kind
        self.apply = apply
        self.describe = describe
        # Some target lines have more than one node of the same AST type
        # (e.g. two Compare nodes in one `and`-joined `if`, or a Constant 0
        # and a Constant 20 in the same test) -- `match_extra`, when given,
        # is an additional predicate checked before accepting a candidate,
        # so the locator keeps searching past a same-type same-line node
        # that isn't the one actually intended.
        self.match_extra = match_extra or (lambda node: True)


def _swap_compare(new_op_cls):
    def _apply(node):
        node.ops[0] = new_op_cls()
        return True
    return _apply


def _bump_constant(delta):
    def _apply(node):
        node.value = node.value + delta
        return True
    return _apply


def _swap_binop(new_op_cls):
    def _apply(node):
        node.op = new_op_cls()
        return True
    return _apply


def _bump_shift_constant(delta):
    def _apply(node):
        # node is the BinOp (Lshift/Rshift), whose integer shift-amount
        # operand is `.right`; or the AugAssign itself (`threshold >>= N`),
        # whose integer operand is `.value`.
        const = node.right if isinstance(node, ast.BinOp) else node.value
        const.value = const.value + delta
        return True
    return _apply


def _swap_minmax(node):
    node.func.id = "max" if node.func.id == "min" else "min"
    return True


def _freeze_assign(node):
    # Replace `ca["field"] = <expr>` with `ca["field"] = ca["field"]`:
    # "deletes" the state update by making it a no-op read-back of the
    # current value, rather than removing the statement (which could change
    # surrounding control flow / leave a dangling branch body).
    new_value = copy.deepcopy(node.targets[0])
    ast.copy_location(new_value, node.value)
    for child in ast.walk(new_value):
        ast.copy_location(child, node.value)
    node.value = new_value
    return True


