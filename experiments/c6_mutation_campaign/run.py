class _Locator(ast.NodeTransformer):
    """Finds the node at (func_name, lineno) matching node_kind (and, when
    more than one node of that kind shares the line, match_extra) within a
    specific top-level function, and applies `apply` to it. Stops after the
    first accepted match; a same-type same-line node that match_extra
    rejects is skipped, not accepted, so the search continues deeper."""

    def __init__(self, func_name, lineno, node_kind, match_extra, apply):
        self.func_name = func_name
        self.lineno = lineno
        self.node_kind = node_kind
        self.match_extra = match_extra
        self.apply = apply
        self.in_target_func = False
        self.found = False

    def visit_FunctionDef(self, node):
        if node.name == self.func_name:
            self.in_target_func = True
            self.generic_visit(node)
            self.in_target_func = False
            return node
        return node

    def generic_visit(self, node):
        if (not self.found and self.in_target_func
                and isinstance(node, self.node_kind) and getattr(node, "lineno", None) == self.lineno
                and self.match_extra(node)):
            self.apply(node)
            self.found = True
            return node
        return super().generic_visit(node)


def build_mutant(target: Target):
    tree = ast.parse(SOURCE_TEXT, filename=str(SOURCE_PATH))
    locator = _Locator(target.func, target.lineno, target.node_kind, target.match_extra, target.apply)
    locator.visit(tree)
    if not locator.found:
        raise RuntimeError(f"{target.id}: could not locate target node (func={target.func} line={target.lineno})")
    ast.fix_missing_locations(tree)

    # Record a human-readable copy for the audit trail. `ast.unparse` may
    # renumber lines (it reformats), so this file is for review only -- the
    # module actually executed below is compiled straight from `tree`,
    # keeping the original source's line numbers intact for coverage.
    mutant_src_for_humans = ast.unparse(tree)
    (MUTANTS_DIR / f"{target.id}.py").write_text(
        f"# Mutant {target.id} ({target.op_class}, callback={target.callback}): {target.describe}\n"
        f"# Reformatted by ast.unparse for readability -- NOT what is executed (see run.py:\n"
        f"# the executed module is compiled directly from the mutated AST, preserving\n"
        f"# user/cubic_model.py's real line numbers for coverage tracking).\n\n"
        + mutant_src_for_humans
    )

    code = compile(tree, filename=str(SOURCE_PATH), mode="exec")
    m = types.ModuleType(f"cubic_mutant_{target.id}")
    m.__file__ = str(SOURCE_PATH)
    exec(code, m.__dict__)
    return m


# --------------------------------------------------------------------------
# Line-coverage tracking for "mutated line executed at least once" via
# sys.monitoring (PEP 669), scoped to just the target function's code object
# so overhead stays limited to the one function under test per mutant run.
# --------------------------------------------------------------------------

_COVERAGE_TOOL_ID = sys.monitoring.COVERAGE_ID


def _find_code_object(module, func_name):
    fn = getattr(module, func_name)
    return fn.__code__


def line_was_executed(module, target: Target, run_fn):
    """Runs `run_fn()` with sys.monitoring LINE events scoped to the target
    function's code object; returns (hit: bool, result, exception)."""
    code_obj = _find_code_object(module, target.func)
    hit = {"value": False}

    def _on_line(code, line_number):
        if code is code_obj and line_number == target.lineno:
            hit["value"] = True
        return sys.monitoring.DISABLE if hit["value"] else None

    sys.monitoring.use_tool_id(_COVERAGE_TOOL_ID, "c6_mutation_campaign")
    try:
        sys.monitoring.register_callback(_COVERAGE_TOOL_ID, sys.monitoring.events.LINE, _on_line)
        sys.monitoring.set_local_events(_COVERAGE_TOOL_ID, code_obj, sys.monitoring.events.LINE)
        result = None
        exc = None
        try:
            result = run_fn()
        except Exception:
            exc = traceback.format_exc()
        return hit["value"], result, exc
    finally:
        sys.monitoring.set_local_events(_COVERAGE_TOOL_ID, code_obj, 0)
        sys.monitoring.register_callback(_COVERAGE_TOOL_ID, sys.monitoring.events.LINE, None)
        sys.monitoring.free_tool_id(_COVERAGE_TOOL_ID)


def main():
    ref_mod = controllers_mod.load_controller("cubic")
    trace_id = [t["id"] for t in traces_mod.list_traces()
                if t["path"] == "raw/cubic_replay/primary/rep1.ccr"][0]
    trace_path = traces_mod.resolve_id(trace_id)
    trace_abi = traces_mod.get_abi(trace_id)

    rows = []
    for target in TARGETS:
        entry = {
            "id": target.id, "operator_class": target.op_class, "callback": target.callback,
            "function": target.func, "line": target.lineno, "description": target.describe,
        }
        try:
            mutant_mod = build_mutant(target)
        except Exception:
            entry["classification"] = "invalid"
            entry["detail"] = traceback.format_exc()
            rows.append(entry)
            print(f"{target.id}: INVALID (build failed)")
            continue

        def _run():
            return all_decisions_core(trace_path, trace_abi, ref_mod, mutant_mod, "A")

        hit, result, exc = line_was_executed(mutant_mod, target, _run)
        entry["mutated_line_executed"] = hit

        if exc is not None:
            entry["classification"] = "crashed"
            entry["detail"] = exc.strip().splitlines()[-1]
            rows.append(entry)
            print(f"{target.id}: CRASHED ({entry['detail']})")
            continue

        n_disagree = result["n_disagree"]
        if n_disagree > 0:
            entry["classification"] = "detected"
            entry["first_divergent_seq"] = result["first_disagreement_seq"]
            entry["first_divergent_callback"] = result.get("first_disagreement_callback")
            entry["n_disagree"] = n_disagree
            rows.append(entry)
            print(f"{target.id}: DETECTED seq={entry['first_divergent_seq']} "
                  f"callback={entry['first_divergent_callback']} n_disagree={n_disagree}")
        elif hit:
            entry["classification"] = "survived_exercised"
            rows.append(entry)
            print(f"{target.id}: SURVIVED (exercised, possibly equivalent)")
        else:
            entry["classification"] = "not_exercised"
            rows.append(entry)
            print(f"{target.id}: NOT EXERCISED (mutated line never ran on this trace)")

    OUT_DIR.joinpath("results.json").write_text(json.dumps(rows, indent=2, default=str))

    counts = {}
    for r in rows:
        counts[r["classification"]] = counts.get(r["classification"], 0) + 1
    print("\n--- summary ---")
    for k, v in sorted(counts.items()):
        print(f"{k}: {v}")
    OUT_DIR.joinpath("counts.json").write_text(json.dumps(counts, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
