"""Replay engine tests (CLAUDE.md section 17):
- same trace + same implementation gives identical replay output;
- reference vs reference yields no first divergence.

The second property is tested against the real, committed R0 traces
(raw/r0/rep*.ccr) when present -- this is the strongest form of the check,
since those traces were generated by the actual target-kernel tcp_reno_*
kfuncs (Oracle C), not by this replay model itself. If the raw traces are
not present (e.g. a checkout that has not run scripts/run_r0.sh on a
Linux/WSL2 host with BPF support), that sub-test is skipped rather than
failed, since it is not this repository's job to fabricate kernel output.
"""
import sys
import os
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from user.replay_r1 import run_r1_on_trace
from user.replay_r2 import run_r2_on_trace

REPO_ROOT = os.path.join(os.path.dirname(__file__), "..")
R0_REP1_CCR = os.path.join(REPO_ROOT, "raw", "r0", "rep1.ccr")
R0_REP1_META = os.path.join(REPO_ROOT, "raw", "r0", "rep1.meta.json")


class TestDeterministicReplay(unittest.TestCase):
    """Same trace + same implementation -> identical replay output,
    run twice."""

    @unittest.skipUnless(os.path.exists(R0_REP1_CCR), "raw/r0/rep1.ccr not present")
    def test_r1_identical_output_on_repeated_run(self):
        result1 = run_r1_on_trace(R0_REP1_CCR, R0_REP1_META)
        result2 = run_r1_on_trace(R0_REP1_CCR, R0_REP1_META)
        self.assertEqual(result1, result2)

    @unittest.skipUnless(os.path.exists(R0_REP1_CCR), "raw/r0/rep1.ccr not present")
    def test_r2_identical_output_on_repeated_run(self):
        result1 = run_r2_on_trace(R0_REP1_CCR, R0_REP1_META)
        result2 = run_r2_on_trace(R0_REP1_CCR, R0_REP1_META)
        self.assertEqual(result1, result2)


class TestReferenceVsReferenceNoFirstDivergence(unittest.TestCase):
    """The real R0 traces were generated by the target kernel's actual
    tcp_reno_* kfuncs (Oracle C) -- an implementation this replay model
    did not author (docs/CORRECTNESS_ORACLES.md). Replaying "reference"
    output through the "reference" model must show first divergence =
    NONE; this is R1/R2 in miniature, re-asserted here as an engine
    property test rather than a gate run.
    """

    @unittest.skipUnless(os.path.exists(R0_REP1_CCR), "raw/r0/rep1.ccr not present")
    def test_r1_zero_mismatches_on_real_kernel_trace(self):
        result = run_r1_on_trace(R0_REP1_CCR, R0_REP1_META)
        self.assertEqual(result["mismatch_count"], 0)
        self.assertGreater(result["n_checked"], 0, "test is vacuous if no events were checked")

    @unittest.skipUnless(os.path.exists(R0_REP1_CCR), "raw/r0/rep1.ccr not present")
    def test_r2_no_first_divergence_on_real_kernel_trace(self):
        result = run_r2_on_trace(R0_REP1_CCR, R0_REP1_META)
        self.assertIsNone(result["first_divergence"])
        self.assertGreater(result["n_checked_before_stop"], 0)


if __name__ == "__main__":
    unittest.main()
